// winJoin joins Windows path elements with '\' regardless of the host OS, so the Windows
// definitions render identically in tests on any platform.
func winJoin(elem ...string) string {
	out := ""
	for i, e := range elem {
		if i == 0 {
			out = strings.TrimRight(e, `\/`)
			continue
		}
		out += `\` + strings.Trim(e, `\/`)
	}
	return out
}

// WindowsScriptPath is the batch file the Scheduled Task runs: it sets the environment, changes
// to the policy directory and appends output to the service log.
func WindowsScriptPath(cfg Config) string {
	return winJoin(cfg.NexusHome, cfg.Name+"-service.cmd")
}

func windowsLogPath(nexusHome string) string { return winJoin(nexusHome, "logs", "service.log") }

// WindowsQuoteArg quotes one argument by the CommandLineToArgvW / MSVC CRT rules.
func WindowsQuoteArg(s string) string {
	if s == "" {
		return `""`
	}
	if !strings.ContainsAny(s, " \t\"") {
		return s
	}
	var b strings.Builder
	b.WriteByte('"')
	slashes := 0
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch c {
		case '\\':
			slashes++
		case '"':
			b.WriteString(strings.Repeat(`\`, slashes+1))
			slashes = 0
		default:
			slashes = 0
		}
		b.WriteByte(c)
	}
	b.WriteString(strings.Repeat(`\`, slashes))
	b.WriteByte('"')
	return b.String()
}

// WindowsCommandLine joins argv with WindowsQuoteArg.
func WindowsCommandLine(argv []string) string {
	q := make([]string, len(argv))
	for i, a := range argv {
		q[i] = WindowsQuoteArg(a)
	}
	return strings.Join(q, " ")
}

// cmdEscape protects text from cmd.exe batch parsing: '%' is doubled and the metacharacters
// (including '"', so cmd never enters quote mode) are caret-escaped. cmd strips the carets, so the
// program receives the text unchanged.
func cmdEscape(s string) string {
	var b strings.Builder
	for _, r := range s {
		switch r {
		case '%':
			b.WriteString("%%")
		case '^', '&', '<', '>', '|', '(', ')', '"':
			b.WriteByte('^')
			b.WriteRune(r)
		default:
			b.WriteRune(r)
		}
	}
	return b.String()
}

// cmdQuotePath double-quotes a path for cmd.exe (Windows paths cannot contain '"').
func cmdQuotePath(p string) string { return `"` + strings.ReplaceAll(p, "%", "%%") + `"` }

// WindowsScript renders the batch file run by the Scheduled Task (CRLF line endings).
func WindowsScript(cfg Config) string {
	lines := []string{
		"@echo off",
		"rem Generated by 'nexus-cli service install'. Re-run it with --force instead of editing.",
	}
	for _, e := range cfg.Env {
		lines = append(lines, "set "+e.Key+"="+cmdEscape(e.Value))
	}
	if cfg.WorkDir != "" {
		lines = append(lines, "cd /d "+cmdQuotePath(cfg.WorkDir))
	}
	argv := cfg.Command()
	cmd := cmdQuotePath(argv[0])
	for _, a := range argv[1:] {
		cmd += " " + cmdEscape(WindowsQuoteArg(a))
	}
	// stdin from NUL: dev sees no terminal and leaves approvals to `nexus-cli approve`.
	cmd += " < NUL >> " + cmdQuotePath(windowsLogPath(cfg.NexusHome)) + " 2>&1"
	lines = append(lines, cmd)
	return strings.Join(lines, "\r\n") + "\r\n"
}

// SchtasksArgs returns the `schtasks` arguments that register the logon task for cfg.
func SchtasksArgs(cfg Config) []string {
	return []string{
		"/Create", "/SC", "ONLOGON", "/TN", cfg.Name,
		"/TR", `"` + WindowsScriptPath(cfg) + `"`,
		"/RL", "LIMITED", "/F",
	}
}

type schtasksManager struct{ o Options }

func (m *schtasksManager) Platform() string { return "schtasks" }
func (m *schtasksManager) Name() string     { return m.o.Name }
func (m *schtasksManager) LogPath() string  { return windowsLogPath(m.o.NexusHome) }

func (m *schtasksManager) DefinitionPath() string {
	return WindowsScriptPath(Config{Name: m.o.Name, NexusHome: m.o.NexusHome})
}

func (m *schtasksManager) Plan(cfg Config) (Plan, error) {
	cfg.Name, cfg.NexusHome = m.o.Name, m.o.NexusHome
	if strings.ContainsRune(cfg.Executable, '"') || strings.ContainsRune(cfg.WorkDir, '"') {
		return Plan{}, errors.New("paths must not contain '\"' on Windows")
	}
	tr := `"` + WindowsScriptPath(cfg) + `"`
	if len(tr) > 261 {
		return Plan{}, fmt.Errorf("task command %s exceeds the 261-character schtasks /TR limit; use a shorter NEXUS_HOME", tr)
	}
	return Plan{
		Files: []File{{Path: m.DefinitionPath(), Content: WindowsScript(cfg), Mode: 0o600}},
		Commands: [][]string{
			append([]string{"schtasks"}, SchtasksArgs(cfg)...),
			{"schtasks", "/Run", "/TN", m.o.Name},
		},
	}, nil
}

func (m *schtasksManager) Install(ctx context.Context, cfg Config, force bool) error {
	existed := exists(m.DefinitionPath())
	if existed && !force {
		return errAlreadyInstalled(m.DefinitionPath())
	}
	p, err := m.Plan(cfg)
	if err != nil {
		return err
	}
	if err := ensureLogDir(m.LogPath()); err != nil {
		return err
	}
	if err := writeFiles(p.Files); err != nil {
		return err
	}
	if existed {
		_ = run(ctx, m.o.Runner, m.end())
	}
	return runAll(ctx, m.o.Runner, p.Commands)
}

func (m *schtasksManager) end() []string { return []string{"schtasks", "/End", "/TN", m.o.Name} }

func (m *schtasksManager) Uninstall(ctx context.Context) error {
	if !exists(m.DefinitionPath()) {
		return ErrNotInstalled
	}
	_ = run(ctx, m.o.Runner, m.end())
	if err := run(ctx, m.o.Runner, []string{"schtasks", "/Delete", "/TN", m.o.Name, "/F"}); err != nil {
		return err
	}
	if err := os.Remove(m.DefinitionPath()); err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	return nil
}

func (m *schtasksManager) Start(ctx context.Context) error {
	if !exists(m.DefinitionPath()) {
		return ErrNotInstalled
	}
	return run(ctx, m.o.Runner, []string{"schtasks", "/Run", "/TN", m.o.Name})
}

func (m *schtasksManager) Stop(ctx context.Context) error {
	if !exists(m.DefinitionPath()) {
		return ErrNotInstalled
	}
	return run(ctx, m.o.Runner, m.end())
}

func (m *schtasksManager) Restart(ctx context.Context) error {
	if !exists(m.DefinitionPath()) {
		return ErrNotInstalled
	}
	_ = run(ctx, m.o.Runner, m.end())
	return run(ctx, m.o.Runner, []string{"schtasks", "/Run", "/TN", m.o.Name})
}

func (m *schtasksManager) Status(ctx context.Context) (Status, error) {
	installed := exists(m.DefinitionPath())
	out, err := m.o.Runner.Output(ctx, "schtasks", "/Query", "/TN", m.o.Name, "/FO", "LIST")
	if err != nil {
		st := Status{Installed: installed, State: "not registered"}
		if !installed {
			st.State = "not installed"
		}
		return st, nil
	}
	st := ParseSchtasksQuery(string(out))
	st.Installed = installed
	return st, nil
}

// ParseSchtasksQuery interprets `schtasks /Query /TN <name> /FO LIST` (English output).
func ParseSchtasksQuery(out string) Status {
	st := Status{State: "unknown"}
	for _, line := range strings.Split(out, "\n") {
		k, v, ok := strings.Cut(line, ":")
		if !ok {
			continue
		}
		k, v = strings.TrimSpace(k), strings.TrimSpace(v)
		switch k {
		case "Status":
			st.State = strings.ToLower(v)
		case "Next Run Time":
			st.Detail = "next run " + v
		}
	}
	st.Running = st.State == "running"
	return st
}

func (m *schtasksManager) Logs(ctx context.Context, w io.Writer, opts LogOptions) error {
	return TailFile(ctx, w, m.LogPath(), opts)
}
