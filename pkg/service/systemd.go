// systemdEscapeSpecifiers doubles '%' so systemd does not expand it as a unit specifier.
func systemdEscapeSpecifiers(s string) string { return strings.ReplaceAll(s, "%", "%%") }

// SystemdQuoteArg quotes one ExecStart= argument following systemd.service(5) rules: '%' and '$'
// are doubled (specifier and variable expansion) and words with whitespace, quotes, backslashes or
// ';' are double-quoted with C-style escapes.
func SystemdQuoteArg(s string) string {
	s = strings.ReplaceAll(systemdEscapeSpecifiers(s), "$", "$$")
	if s != "" && !strings.ContainsAny(s, " \t\"'\\;") {
		return s
	}
	return `"` + systemdCEscape(s) + `"`
}

func systemdCEscape(s string) string {
	return strings.NewReplacer(`\`, `\\`, `"`, `\"`, "\t", `\t`).Replace(s)
}

// systemdQuoteValue double-quotes a whole setting value (Environment=, ReadWritePaths=).
func systemdQuoteValue(s string) string {
	return `"` + systemdCEscape(systemdEscapeSpecifiers(s)) + `"`
}

// UnitName is the systemd unit name for a service name.
func UnitName(name string) string { return name + ".service" }

// SystemdUnit renders the systemd user unit for cfg.
func SystemdUnit(cfg Config) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	w("# Generated by 'nexus-cli service install'. Re-run it with --force instead of editing.")
	w("[Unit]")
	w("Description=nexus-cli zero-trust proxy (%s)", systemdEscapeSpecifiers(cfg.Listen))
	w("Documentation=https://github.com/whoisnjoguu/nexus-cli/blob/main/docs/service.md")
	w("")
	w("[Service]")
	w("Type=simple")
	argv := cfg.Command()
	q := make([]string, len(argv))
	for i, a := range argv {
		q[i] = SystemdQuoteArg(a)
	}
	w("ExecStart=%s", strings.Join(q, " "))
	if cfg.WorkDir != "" {
		// '-': a missing directory falls back to $HOME instead of failing the unit.
		w("WorkingDirectory=-%s", systemdEscapeSpecifiers(cfg.WorkDir))
	}
	for _, e := range cfg.Env {
		w("Environment=%s", systemdQuoteValue(e.Key+"="+e.Value))
	}
	w("Restart=on-failure")
	w("RestartSec=2")
	w("UMask=0077")
	if cfg.Hardening {
		w("NoNewPrivileges=yes")
		w("PrivateTmp=yes")
		w("ProtectSystem=strict")
		for _, p := range systemdWritablePaths(cfg) {
			// '-': skip paths that do not exist yet instead of failing the unit.
			w("ReadWritePaths=%s", systemdQuoteValue("-"+p))
		}
	}
	w("")
	w("[Install]")
	w("WantedBy=default.target")
	return b.String()
}

// systemdWritablePaths are the paths dev writes: NEXUS_HOME (keys, audit, discovery, CA) and the
// policy directory ("always allow" answers are persisted into the policy file).
func systemdWritablePaths(cfg Config) []string {
	var out []string
	seen := map[string]bool{}
	for _, p := range []string{cfg.NexusHome, filepath.Dir(cfg.Policy)} {
		if p == "" || seen[p] {
			continue
		}
		seen[p] = true
		out = append(out, p)
	}
	return out
}

type systemdManager struct{ o Options }

func (m *systemdManager) Platform() string { return "systemd" }
func (m *systemdManager) Name() string     { return m.o.Name }
func (m *systemdManager) LogPath() string  { return "" }
func (m *systemdManager) unit() string     { return UnitName(m.o.Name) }

func (m *systemdManager) DefinitionPath() string {
	return filepath.Join(m.o.ConfigHome, "systemd", "user", m.unit())
}

func (m *systemdManager) ctl(args ...string) []string {
	return append([]string{"systemctl", "--user"}, args...)
}

func (m *systemdManager) Plan(cfg Config) (Plan, error) {
	cfg.Name, cfg.NexusHome = m.o.Name, m.o.NexusHome
	return Plan{
		Files: []File{{Path: m.DefinitionPath(), Content: SystemdUnit(cfg), Mode: 0o644}},
		Commands: [][]string{
			m.ctl("daemon-reload"),
			m.ctl("enable", "--now", m.unit()),
		},
	}, nil
}

func (m *systemdManager) Install(ctx context.Context, cfg Config, force bool) error {
	existed := exists(m.DefinitionPath())
	if existed && !force {
		return errAlreadyInstalled(m.DefinitionPath())
	}
	p, err := m.Plan(cfg)
	if err != nil {
		return err
	}
	if err := writeFiles(p.Files); err != nil {
		return err
	}
	if err := runAll(ctx, m.o.Runner, p.Commands); err != nil {
		return err
	}
	if existed {
		// enable --now leaves an already running instance on the old definition.
		return run(ctx, m.o.Runner, m.ctl("restart", m.unit()))
	}
	return nil
}

func (m *systemdManager) Uninstall(ctx context.Context) error {
	if !exists(m.DefinitionPath()) {
		return ErrNotInstalled
	}
	if err := run(ctx, m.o.Runner, m.ctl("disable", "--now", m.unit())); err != nil {
		return err
	}
	if err := os.Remove(m.DefinitionPath()); err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	if err := run(ctx, m.o.Runner, m.ctl("daemon-reload")); err != nil {
		return err
	}
	// Forget a failed state so the unit name disappears from `systemctl --user --failed`.
	_ = run(ctx, m.o.Runner, m.ctl("reset-failed", m.unit()))
	return nil
}

func (m *systemdManager) requireInstalled() error {
	if !exists(m.DefinitionPath()) {
		return ErrNotInstalled
	}
	return nil
}

func (m *systemdManager) Start(ctx context.Context) error {
	if err := m.requireInstalled(); err != nil {
		return err
	}
	return run(ctx, m.o.Runner, m.ctl("start", m.unit()))
}

func (m *systemdManager) Stop(ctx context.Context) error {
	if err := m.requireInstalled(); err != nil {
		return err
	}
	return run(ctx, m.o.Runner, m.ctl("stop", m.unit()))
}

func (m *systemdManager) Restart(ctx context.Context) error {
	if err := m.requireInstalled(); err != nil {
		return err
	}
	return run(ctx, m.o.Runner, m.ctl("restart", m.unit()))
}

func (m *systemdManager) Status(ctx context.Context) (Status, error) {
	installed := exists(m.DefinitionPath())
	argv := m.ctl("show", m.unit(), "--property=LoadState,ActiveState,SubState,MainPID,Result")
	out, err := m.o.Runner.Output(ctx, argv[0], argv[1:]...)
	if err != nil {
		return Status{Installed: installed, State: "unknown"},
			fmt.Errorf("%s: %w: %s", strings.Join(argv, " "), err, strings.TrimSpace(string(out)))
	}
	st := ParseSystemctlShow(string(out))
	// Installed means our unit file exists; a stale LoadState=loaded lingers until daemon-reload.
	st.Installed = installed
	return st, nil
}

// ParseSystemctlShow interprets `systemctl show --property=LoadState,ActiveState,SubState,MainPID,Result`.
func ParseSystemctlShow(out string) Status {
	kv := map[string]string{}
	for _, line := range strings.Split(out, "\n") {
		if k, v, ok := strings.Cut(strings.TrimSpace(line), "="); ok {
			kv[k] = v
		}
	}
	st := Status{State: kv["ActiveState"]}
	if st.State == "" {
		st.State = "unknown"
	}
	st.Installed = kv["LoadState"] == "loaded"
	st.Running = kv["ActiveState"] == "active"
	if pid, err := strconv.Atoi(kv["MainPID"]); err == nil && pid > 0 {
		st.PID = pid
	}
	var detail []string
	if s := kv["SubState"]; s != "" && s != st.State {
		detail = append(detail, "sub-state "+s)
	}
	if r := kv["Result"]; r != "" && r != "success" {
		detail = append(detail, "result "+r)
	}
	if l := kv["LoadState"]; l != "" && l != "loaded" {
		detail = append(detail, "load-state "+l)
	}
	st.Detail = strings.Join(detail, ", ")
	return st
}

func (m *systemdManager) Logs(ctx context.Context, w io.Writer, opts LogOptions) error {
	args := []string{"--user", "-u", m.unit(), "--no-pager", "-o", "short-iso"}
	if opts.Lines > 0 {
		args = append(args, "-n", strconv.Itoa(opts.Lines))
	}
	if opts.Follow {
		args = append(args, "-f")
	}
	return m.o.Runner.Stream(ctx, w, "journalctl", args...)
}
