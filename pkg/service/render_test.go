// unquoteSystemd splits an ExecStart= value the way systemd does (quotes, C escapes, %%, $$).
func unquoteSystemd(t *testing.T, s string) []string {
	t.Helper()
	var out []string
	var cur strings.Builder
	inWord, inQuote := false, false
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c == '%' || c == '$':
			if i+1 >= len(s) || s[i+1] != c {
				t.Fatalf("unescaped %c in %q", c, s)
			}
			cur.WriteByte(c)
			i++
			inWord = true
		case inQuote && c == '\\':
			i++
			switch s[i] {
			case 't':
				cur.WriteByte('\t')
			default:
				cur.WriteByte(s[i])
			}
		case c == '"':
			inQuote = !inQuote
			inWord = true
		case !inQuote && (c == ' ' || c == '\t'):
			if inWord {
				out = append(out, cur.String())
				cur.Reset()
				inWord = false
			}
		case !inQuote && (c == '\\' || c == '\''):
			t.Fatalf("unquoted %c in %q", c, s)
		default:
			cur.WriteByte(c)
			inWord = true
		}
	}
	if inQuote {
		t.Fatalf("unterminated quote in %q", s)
	}
	if inWord {
		out = append(out, cur.String())
	}
	return out
}

func TestSystemdQuoteRoundTrip(t *testing.T) {
	for _, s := range []string{"plain", "", "a b", `q"uote`, `back\slash`, "50%", "$HOME", "semi;colon", "it's", "tab\there", "&<>|"} {
		got := unquoteSystemd(t, SystemdQuoteArg(s))
		if len(got) != 1 || got[0] != s {
			t.Errorf("SystemdQuoteArg(%q) = %s, round trip %q", s, SystemdQuoteArg(s), got)
		}
	}
	line := strings.TrimPrefix(lineWith(t, SystemdUnit(posixCfg()), "ExecStart="), "ExecStart=")
	if got, want := unquoteSystemd(t, line), posixCfg().Command(); strings.Join(got, "\x00") != strings.Join(want, "\x00") {
		t.Fatalf("ExecStart round trip:\n got %q\nwant %q", got, want)
	}
}

func lineWith(t *testing.T, s, prefix string) string {
	t.Helper()
	for _, l := range strings.Split(s, "\n") {
		if strings.HasPrefix(l, prefix) {
			return l
		}
	}
	t.Fatalf("no line starting with %q", prefix)
	return ""
}

