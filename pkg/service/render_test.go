// parseWindowsArgs implements the MSVC CRT command-line splitting rules (post-2008).
func parseWindowsArgs(s string) []string {
	var out []string
	var cur strings.Builder
	inQuote, inWord := false, false
	for i := 0; i < len(s); {
		c := s[i]
		switch {
		case c == '\\':
			n := 0
			for i < len(s) && s[i] == '\\' {
				n++
				i++
			}
			if i < len(s) && s[i] == '"' {
				cur.WriteString(strings.Repeat(`\`, n/2))
				if n%2 == 1 {
					cur.WriteByte('"')
					i++
				}
			} else {
				cur.WriteString(strings.Repeat(`\`, n))
			}
			inWord = true
			continue
		case c == '"':
			if inQuote && i+1 < len(s) && s[i+1] == '"' {
				cur.WriteByte('"')
				i += 2
				continue
			}
			inQuote = !inQuote
			inWord = true
		case !inQuote && (c == ' ' || c == '\t'):
			if inWord {
				out = append(out, cur.String())
				cur.Reset()
				inWord = false
			}
		default:
			cur.WriteByte(c)
			inWord = true
		}
		i++
	}
	if inWord {
		out = append(out, cur.String())
	}
	return out
}

func TestWindowsQuoteArgRoundTrip(t *testing.T) {
	cases := []string{"plain", "", "a b", `C:\a b\`, `C:\dir\`, `q"uote`, `a\"b`, `trail\\`, `x "y" \\"z`, "&<>|^%"}
	for _, s := range cases {
		got := parseWindowsArgs(WindowsQuoteArg(s))
		if len(got) != 1 || got[0] != s {
			t.Errorf("WindowsQuoteArg(%q) = %s, parsed back %q", s, WindowsQuoteArg(s), got)
		}
	}
	argv := windowsCfg().Command()
	if got := parseWindowsArgs(WindowsCommandLine(argv)); strings.Join(got, "\x00") != strings.Join(argv, "\x00") {
		t.Fatalf("command line round trip:\n got %q\nwant %q", got, argv)
	}
}

// uncmd undoes cmd.exe phase-2 escaping for an unquoted span: '^x' -> 'x', '%%' -> '%'.
func uncmd(s string) string {
	var b strings.Builder
	for i := 0; i < len(s); i++ {
		switch {
		case s[i] == '^' && i+1 < len(s):
			i++
			b.WriteByte(s[i])
		case s[i] == '%' && i+1 < len(s) && s[i+1] == '%':
			i++
			b.WriteByte('%')
		default:
			b.WriteByte(s[i])
		}
	}
	return b.String()
}

func TestWindowsScriptCommandRoundTrip(t *testing.T) {
	cfg := windowsCfg()
	script := WindowsScript(cfg)
	var cmdLine string
	for _, l := range strings.Split(script, "\r\n") {
		if strings.HasPrefix(l, `"C:\Program Files`) {
			cmdLine = l
		}
		if strings.HasPrefix(l, "set FOO=") {
			if got := uncmd(strings.TrimPrefix(l, "set FOO=")); got != cfg.Env[1].Value {
				t.Errorf("set FOO round trip = %q, want %q", got, cfg.Env[1].Value)
			}
		}
	}
	exe := `"C:\Program Files\Nexus 100%%\nexus-cli.exe" `
	if !strings.HasPrefix(cmdLine, exe) {
		t.Fatalf("command line %q lacks the quoted executable", cmdLine)
	}
	rest, _, ok := strings.Cut(strings.TrimPrefix(cmdLine, exe), " < NUL >> ")
	if !ok {
		t.Fatalf("command line %q lacks the redirections", cmdLine)
	}
	if got, want := parseWindowsArgs(uncmd(rest)), cfg.DevArgs(); strings.Join(got, "\x00") != strings.Join(want, "\x00") {
		t.Fatalf("args round trip:\n got %q\nwant %q", got, want)
	}
}

func TestListenFromDefinition(t *testing.T) {
	cfg := posixCfg()
	cfg.Listen = "127.0.0.1:9123"
	for name, def := range map[string]string{
		"systemd": SystemdUnit(cfg),
		"launchd": LaunchdPlist(cfg),
		"windows": WindowsScript(func() Config { c := windowsCfg(); c.Listen = cfg.Listen; return c }()),
	} {
		if got := ListenFromDefinition(def); got != "127.0.0.1:9123" {
			t.Errorf("%s: ListenFromDefinition = %q", name, got)
		}
	}
	if got := ListenFromDefinition("nothing here"); got != "" {
		t.Errorf("ListenFromDefinition(garbage) = %q", got)
	}
}
