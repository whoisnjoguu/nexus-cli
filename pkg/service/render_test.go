// TestLaunchdPlistParses decodes the plist with a real XML parser and checks values survive.
func TestLaunchdPlistParses(t *testing.T) {
	cfg := posixCfg()
	dec := xml.NewDecoder(strings.NewReader(LaunchdPlist(cfg)))
	dec.Strict = true
	var strs []string
	for {
		tok, err := dec.Token()
		if err == io.EOF {
			break
		}
		if err != nil {
			t.Fatalf("plist is not well-formed XML: %v", err)
		}
		if se, ok := tok.(xml.StartElement); ok && se.Name.Local == "string" {
			var s string
			if err := dec.DecodeElement(&s, &se); err != nil {
				t.Fatal(err)
			}
			strs = append(strs, s)
		}
	}
	joined := "\x00" + strings.Join(strs, "\x00") + "\x00"
	for _, want := range append(cfg.Command(), cfg.Env[1].Value, cfg.WorkDir) {
		if !strings.Contains(joined, "\x00"+want+"\x00") {
			t.Errorf("value %q not found in decoded plist strings %q", want, strs)
		}
	}
}

