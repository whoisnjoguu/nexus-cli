// LaunchdLabel is the launchd job label for a service name (dev.nexus-cli by default).
func LaunchdLabel(name string) string { return "dev." + name }

// launchdLogPath is where the agent's stdout/stderr go: $NEXUS_HOME/logs/service.log.
func launchdLogPath(nexusHome string) string { return path.Join(nexusHome, "logs", "service.log") }

func xmlEscape(s string) string {
	var b strings.Builder
	_ = xml.EscapeText(&b, []byte(s))
	return b.String()
}

// LaunchdPlist renders the launchd agent for cfg. Every value is XML-escaped.
func LaunchdPlist(cfg Config) string {
	var b strings.Builder
	w := func(s string) { b.WriteString(s + "\n") }
	str := func(indent, s string) { w(indent + "<string>" + xmlEscape(s) + "</string>") }
	key := func(indent, s string) { w(indent + "<key>" + xmlEscape(s) + "</key>") }
	logPath := launchdLogPath(cfg.NexusHome)

	w(`<?xml version="1.0" encoding="UTF-8"?>`)
	w(`<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">`)
	w(`<!-- Generated by 'nexus-cli service install'. Reinstall (with the force flag) instead of editing. -->`)
	w(`<plist version="1.0">`)
	w(`<dict>`)
	key("  ", "Label")
	str("  ", LaunchdLabel(cfg.Name))
	key("  ", "ProgramArguments")
	w("  <array>")
	for _, a := range cfg.Command() {
		str("    ", a)
	}
	w("  </array>")
	if len(cfg.Env) > 0 {
		key("  ", "EnvironmentVariables")
		w("  <dict>")
		for _, e := range cfg.Env {
			key("    ", e.Key)
			str("    ", e.Value)
		}
		w("  </dict>")
	}
	if cfg.WorkDir != "" {
		key("  ", "WorkingDirectory")
		str("  ", cfg.WorkDir)
	}
	key("  ", "RunAtLoad")
	w("  <true/>")
	key("  ", "KeepAlive")
	w("  <dict>")
	key("    ", "SuccessfulExit")
	w("    <false/>")
	w("  </dict>")
	key("  ", "ThrottleInterval")
	w("  <integer>10</integer>")
	key("  ", "Umask")
	w("  <integer>63</integer>")
	key("  ", "ProcessType")
	str("  ", "Background")
	key("  ", "StandardOutPath")
	str("  ", logPath)
	key("  ", "StandardErrorPath")
	str("  ", logPath)
	w(`</dict>`)
	w(`</plist>`)
	return b.String()
}

type launchdManager struct{ o Options }

func (m *launchdManager) Platform() string { return "launchd" }
func (m *launchdManager) Name() string     { return m.o.Name }
func (m *launchdManager) label() string    { return LaunchdLabel(m.o.Name) }
func (m *launchdManager) domain() string   { return "gui/" + strconv.Itoa(m.o.UID) }
func (m *launchdManager) target() string   { return m.domain() + "/" + m.label() }
func (m *launchdManager) LogPath() string  { return launchdLogPath(m.o.NexusHome) }

func (m *launchdManager) DefinitionPath() string {
	return filepath.Join(m.o.HomeDir, "Library", "LaunchAgents", m.label()+".plist")
}

func (m *launchdManager) bootstrap() []string {
	return []string{"launchctl", "bootstrap", m.domain(), m.DefinitionPath()}
}

func (m *launchdManager) Plan(cfg Config) (Plan, error) {
	cfg.Name, cfg.NexusHome = m.o.Name, m.o.NexusHome
	return Plan{
		Files:    []File{{Path: m.DefinitionPath(), Content: LaunchdPlist(cfg), Mode: 0o644}},
		Commands: [][]string{m.bootstrap()},
	}, nil
}

// load bootstraps the agent, falling back to the legacy `launchctl load -w`.
func (m *launchdManager) load(ctx context.Context) error {
	err := run(ctx, m.o.Runner, m.bootstrap())
	if err == nil {
		return nil
	}
	if ferr := run(ctx, m.o.Runner, []string{"launchctl", "load", "-w", m.DefinitionPath()}); ferr != nil {
		return fmt.Errorf("%w (fallback: %v)", err, ferr)
	}
	return nil
}

func (m *launchdManager) unload(ctx context.Context) error {
	err := run(ctx, m.o.Runner, []string{"launchctl", "bootout", m.target()})
	if err == nil {
		return nil
	}
	if ferr := run(ctx, m.o.Runner, []string{"launchctl", "unload", "-w", m.DefinitionPath()}); ferr != nil {
		return fmt.Errorf("%w (fallback: %v)", err, ferr)
	}
	return nil
}

func (m *launchdManager) Install(ctx context.Context, cfg Config, force bool) error {
	existed := exists(m.DefinitionPath())
	if existed && !force {
		return errAlreadyInstalled(m.DefinitionPath())
	}
	if err := ensureLogDir(m.LogPath()); err != nil {
		return err
	}
	if existed {
		_ = m.unload(ctx)
	}
	p, _ := m.Plan(cfg)
	if err := writeFiles(p.Files); err != nil {
		return err
	}
	return m.load(ctx)
}

func (m *launchdManager) Uninstall(ctx context.Context) error {
	if !exists(m.DefinitionPath()) {
		return ErrNotInstalled
	}
	// A job that is already unloaded makes bootout fail; removing the plist is what matters.
	_ = m.unload(ctx)
	if err := os.Remove(m.DefinitionPath()); err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	return nil
}

func (m *launchdManager) Start(ctx context.Context) error {
	if !exists(m.DefinitionPath()) {
		return ErrNotInstalled
	}
	if err := run(ctx, m.o.Runner, []string{"launchctl", "kickstart", m.target()}); err != nil {
		// Not loaded (e.g. after `launchctl bootout`): loading starts it (RunAtLoad).
		return m.load(ctx)
	}
	return nil
}

func (m *launchdManager) Stop(ctx context.Context) error {
	if !exists(m.DefinitionPath()) {
		return ErrNotInstalled
	}
	// dev exits 0 on SIGTERM, which KeepAlive{SuccessfulExit=false} does not restart.
	return run(ctx, m.o.Runner, []string{"launchctl", "kill", "SIGTERM", m.target()})
}

func (m *launchdManager) Restart(ctx context.Context) error {
	if !exists(m.DefinitionPath()) {
		return ErrNotInstalled
	}
	if err := run(ctx, m.o.Runner, []string{"launchctl", "kickstart", "-k", m.target()}); err != nil {
		return m.load(ctx)
	}
	return nil
}

func (m *launchdManager) Status(ctx context.Context) (Status, error) {
	installed := exists(m.DefinitionPath())
	out, err := m.o.Runner.Output(ctx, "launchctl", "print", m.target())
	if err != nil {
		// launchctl print exits non-zero (113) when the job is not loaded.
		st := Status{Installed: installed, State: "not loaded"}
		if !installed {
			st.State = "not installed"
		}
		return st, nil
	}
	st := ParseLaunchctlPrint(string(out))
	st.Installed = installed
	return st, nil
}

// ParseLaunchctlPrint interprets the top-level fields of `launchctl print gui/<uid>/<label>`.
func ParseLaunchctlPrint(out string) Status {
	st := Status{State: "unknown"}
	var lastExit string
	sc := bufio.NewScanner(strings.NewReader(out))
	for sc.Scan() {
		line := sc.Text()
		// Top-level properties are indented by exactly one tab; nested blocks by more.
		if !strings.HasPrefix(line, "\t") || strings.HasPrefix(line, "\t\t") {
			continue
		}
		k, v, ok := strings.Cut(strings.TrimSpace(line), " = ")
		if !ok {
			continue
		}
		switch k {
		case "state":
			st.State = v
		case "pid":
			if pid, err := strconv.Atoi(v); err == nil {
				st.PID = pid
			}
		case "last exit code":
			lastExit = v
		}
	}
	st.Running = st.State == "running"
	if lastExit != "" {
		st.Detail = "last exit code " + lastExit
	}
	return st
}

func (m *launchdManager) Logs(ctx context.Context, w io.Writer, opts LogOptions) error {
	return TailFile(ctx, w, m.LogPath(), opts)
}
